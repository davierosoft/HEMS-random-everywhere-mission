#!/usr/bin/env node
'use strict';

// Owner rule of 2026-10-23: BEGIN HOISTING and BEGIN SKID LNDG OPS (crash site approach) and the hoist commands of the heli rescuer (BEGIN HOISTING UP in pick heli
// rescuer, BEGIN HOISTING DOWN in drop heli rescuer) must not be offered together when the heli rescuer point is inside the landing spot: the scene commands could
// bypass the pick-up or the drop of the heli rescuer and block the mission. One local flag, hr_scene_block, set where the heli rescuer command is created and read by the
// four show conditions of the scene commands. Static check of the production sources; the buttons themselves are HPG runtime behaviour (PENDING).
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const dir = path.join(root, 'mission-src', 'macros');
const macros = {};
for (const file of fs.readdirSync(dir).filter((name) => name.endsWith('.json'))) Object.assign(macros, JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8')));
const text = (value) => JSON.stringify(value);
const set = (value) => `{"set":{"local":"hr_scene_block"},"value":${value}}`;
const inSpot = '{"if":{"has_location":"landing_spot"},"eq":1,"then":[{"if":{"location":"heli_rescuer_location","var":"distance:m","to":"landing_spot"},"lt":{"global":"LANDING_SPOT_HOIST"},"then":[' + set(1) + ']}]}';

// 1. the heli rescuer commands set the flag when they are created and clear it at the click, at the destroy and at the start of the macro
for (const [name, id] of [['pick heli rescuer', 'begin_hoist_up'], ['drop heli rescuer', 'begin_hoist_dwn']]) {
  const body = text(macros[name]);
  assert.ok(body.startsWith(`[${text(macros[name][0])}`) && body.includes(set(0)), `${name}: the flag exists`);
  const create = body.indexOf(`"create_user_action":{"id":"${id}"`);
  assert.ok(create > 0, `${name}: the command ${id} is created`);
  const before = body.slice(0, create);
  assert.ok(before.endsWith(`${inSpot},{`), `${name}: the flag is computed right before ${id} is created (point inside the landing spot)`);
  const click = body.slice(create, body.indexOf('"show_condition"', create));
  assert.ok(click.includes(`"click_commands":[`) && click.includes(set(0)), `${name}: the click clears the flag`);
  const destroy = body.indexOf(`{"destroy_user_action":"${id}"}]},${set(0)}`);
  assert.ok(destroy > create, `${name}: the destroy path clears the flag`);
  assert.ok(text(macros[name].slice(0, 3)).includes(set(0)), `${name}: the macro clears the flag at its start`);
}

// 2. the four scene commands read it
const gate = '{"require":{"local":"hr_scene_block"},"ne":1}]},"eq":1}';
const seen = [];
(function walk(node) {
  if (Array.isArray(node)) return node.forEach(walk);
  if (!node || typeof node !== 'object') return;
  const a = node.create_user_action;
  if (a && (a.id === 'begin_hoisting' || a.id === 'skid_landing')) seen.push([a.id, text(a.show_condition)]);
  for (const v of Object.values(node)) walk(v);
}(macros['crash site approach']));
assert.equal(seen.length, 4, 'two definitions of begin_hoisting and two of skid_landing');
for (const [id, show] of seen) assert.ok(show.endsWith(gate), `${id} reads hr_scene_block`);
assert.deepEqual(seen.map((s) => s[0]).sort(), ['begin_hoisting', 'begin_hoisting', 'skid_landing', 'skid_landing']);
// 3. a new dispatch starts clean
assert.ok(text(macros.objective1).includes(set(0)), 'objective1 clears the flag');

// 4. nothing else reads the flag: the heli rescuer commands never wait for the scene commands (no deadlock between the two)
let readers = 0;
// the speech bridge copies the visibility condition of the scene commands (generated by tools/speech-bridge.js, kept equal by test-speech-bridge.js)
for (const [name, body] of Object.entries(macros)) if (text(body).includes('{"require":{"local":"hr_scene_block"}')) readers += name === 'crash site approach' ? 1 : name === 'speech availability' || name === 'speech action run' ? 0 : 100;
assert.equal(readers, 1, 'only crash site approach (and the generated speech bridge copies of its condition) reads hr_scene_block');

console.log('HR scene block PASS: the flag is set before BEGIN HOISTING UP and DOWN, cleared at click, destroy, macro start and dispatch reset, and read by the four scene command conditions only. Simulator runtime PENDING.');
